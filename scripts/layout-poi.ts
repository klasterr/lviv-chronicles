// Turns the OSM point features (data/osm-poi.json, see fetch-poi.ts) and the footprints/roads into the avenue's "real world" layer:
// shop signs on the street-facing walls, benches/bins/lamps/trees/bike racks/hydrants/stops at their mapped positions, zebra crossings,
// and kerb bollards. Everything is derived from OSM data; nothing is placed by hand.
type Pt = number[]
export interface PoiNode { lat: number; lon: number; t: Record<string, string> }
interface Bld { id: string; r: Pt[][] }
interface Road { p: Pt[]; k: string; w: number }

const r2 = (v: number) => +v.toFixed(2)
const segNear = (p: Pt, a: Pt, b: Pt) => {
  const dx = b[0] - a[0], dz = b[1] - a[1], t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dz) / (dx * dx + dz * dz || 1)))
  const q = [a[0] + dx * t, a[1] + dz * t]
  return { d: Math.hypot(p[0] - q[0], p[1] - q[1]), q, t }
}
const nearLines = (p: Pt, lines: Pt[][]) => {
  let best = { d: Infinity, q: [0, 0], a: [0, 0], b: [1, 0] }
  for (const l of lines) for (let i = 0; i < l.length - 1; i++) { const s = segNear(p, l[i], l[i + 1]); if (s.d < best.d) best = { d: s.d, q: s.q, a: l[i], b: l[i + 1] } }
  return best
}
const inside = (p: Pt, r: Pt[]) => { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) if ((r[i][1] > p[1]) !== (r[j][1] > p[1]) && p[0] < ((r[j][0] - r[i][0]) * (p[1] - r[i][1])) / (r[j][1] - r[i][1]) + r[i][0]) c = !c; return c }
const area = (r: Pt[]) => r.reduce((s, p, i) => s + (p[0] * r[(i + 1) % r.length][1] - r[(i + 1) % r.length][0] * p[1]), 0) / 2

const SIGN_AMENITY = new Set(['cafe', 'restaurant', 'fast_food', 'bar', 'pub', 'bank', 'pharmacy', 'cinema', 'theatre', 'ice_cream', 'nightclub', 'casino'])
const SIGN_TOURISM = new Set(['hotel', 'hostel', 'museum', 'gallery'])

export function layoutPoi(poi: PoiNode[], proj: (c: number[]) => number[], buildings: Bld[], roads: Road[], avenue: Pt[][], generated: { trees: number[][]; benches: number[][]; lamps: number[][] }, skipSignBuildings: string[]) {
  const near = (p: Pt, d: number) => nearLines(p, avenue).d <= d
  const streets = roads.filter((r) => ['primary', 'secondary', 'tertiary', 'residential', 'pedestrian', 'service'].includes(r.k)).map((r) => r.p)
  const nodes = poi.map((e) => ({ p: proj([e.lon, e.lat]), t: e.t }))
  const dedupe = (p: Pt, list: number[][], d: number) => list.some((q) => Math.hypot(q[0] - p[0], q[1] - p[1]) < d)

  // ---- shop signs
  const texts: string[] = [], signs: number[][] = []
  const placed = new Map<string, number[]>() // wall key -> sign centres along the wall
  const cand = nodes.filter((n) => n.t.name && !/mcdonald/i.test(n.t.brand ?? n.t.name) && (n.t.shop || SIGN_AMENITY.has(n.t.amenity) || SIGN_TOURISM.has(n.t.tourism)) && near(n.p, 60))
    .sort((a, b) => nearLines(a.p, avenue).d - nearLines(b.p, avenue).d)
  for (const n of cand) {
    let bld = buildings.find((b) => inside(n.p, b.r[0]))
    if (!bld) { let best = 3; for (const b of buildings) for (let i = 0; i < b.r[0].length; i++) { const s = segNear(n.p, b.r[0][i], b.r[0][(i + 1) % b.r[0].length]); if (s.d < best) { best = s.d; bld = b } } }
    if (!bld || skipSignBuildings.includes(bld.id)) continue
    const ring = area(bld.r[0]) > 0 ? bld.r[0] : [...bld.r[0]].reverse()
    let pick: { i: number; score: number; t: number; len: number; n: Pt; a: Pt; dx: number; dz: number } | null = null
    for (let i = 0; i < ring.length; i++) {
      const a = ring[i], b = ring[(i + 1) % ring.length], dx = b[0] - a[0], dz = b[1] - a[1], len = Math.hypot(dx, dz)
      if (len < 2) continue
      const nn = [dz / len, -dx / len], s = segNear(n.p, a, b), mid = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2], st = nearLines(mid, streets)
      const facing = st.d < 22 && nn[0] * ((st.q[0] - mid[0]) / (st.d || 1)) + nn[1] * ((st.q[1] - mid[1]) / (st.d || 1)) > 0.6
      const score = s.d + (facing ? 0 : 100)
      if (!pick || score < pick.score) pick = { i, score, t: s.t * len, len, n: nn, a, dx: dx / len, dz: dz / len }
    }
    if (!pick || pick.score > 16) continue
    const label = (n.t['name:uk'] ?? n.t.name).replace(/\s*[(—-].*$/, '').slice(0, 26)
    const w = Math.min(4.2, Math.max(1.5, 0.3 + 0.2 * label.length), pick.len - 0.8)
    if (w < 1.3) continue
    const t = Math.max(w / 2 + 0.4, Math.min(pick.len - w / 2 - 0.4, pick.t)), key = bld.id + '#' + pick.i, list = placed.get(key) ?? []
    if (list.some((c) => Math.abs(c - t) < w / 2 + 1.0)) continue
    list.push(t); placed.set(key, list)
    let ti = texts.indexOf(label); if (ti < 0) { texts.push(label); ti = texts.length - 1 }
    signs.push([r2(pick.a[0] + pick.dx * t), r2(pick.a[1] + pick.dz * t), r2(pick.n[0]), r2(pick.n[1]), r2(w), ti])
    if (signs.length >= 120) break
  }

  // ---- mapped street furniture and trees close to the avenue (the boulevard rows are generated by layout-avenue.ts; skip duplicates)
  const pick2 = (f: (t: Record<string, string>) => boolean, d: number) => nodes.filter((n) => f(n.t) && near(n.p, d))
  const yawToward = (p: Pt) => { // benches: face the nearest street, i.e. backrest towards the building behind them
    const s = nearLines(p, streets); return r2(Math.atan2(s.q[0] - p[0], s.q[1] - p[1]))
  }
  const osm = {
    benches: pick2((t) => t.amenity === 'bench', 150).filter((n) => !dedupe(n.p, generated.benches, 2.2)).map((n) => [r2(n.p[0]), r2(n.p[1]), yawToward(n.p)]),
    bins: pick2((t) => t.amenity === 'waste_basket', 150).map((n) => [r2(n.p[0]), r2(n.p[1])]),
    bikes: pick2((t) => t.amenity === 'bicycle_parking', 150).map((n) => [r2(n.p[0]), r2(n.p[1]), yawToward(n.p)]),
    lamps: pick2((t) => t.highway === 'street_lamp', 150).filter((n) => !dedupe(n.p, generated.lamps, 3)).map((n) => [r2(n.p[0]), r2(n.p[1]), yawToward(n.p)]),
    hydrants: pick2((t) => t.emergency === 'fire_hydrant', 120).map((n) => [r2(n.p[0]), r2(n.p[1])]),
    stops: pick2((t) => t.highway === 'bus_stop', 150).map((n) => [r2(n.p[0]), r2(n.p[1]), yawToward(n.p)]),
    trees: pick2((t) => t.natural === 'tree', 130).filter((n) => !dedupe(n.p, generated.trees, 2.5)).map((n, i) => [r2(n.p[0]), r2(n.p[1]), i + 200, 2]),
  }

  // ---- zebra crossings: OSM crossing nodes lying on a carriageway; oriented along the road
  const crossings: number[][] = []
  for (const n of pick2((t) => t.highway === 'crossing' && t.crossing !== 'unmarked' && t['crossing:markings'] !== 'no', 150)) {
    let best: { d: number; r: Road; a: Pt; b: Pt } | null = null
    for (const r of roads) if (['primary', 'secondary', 'tertiary', 'residential', 'service'].includes(r.k)) { const s = nearLines(n.p, [r.p]); if (!best || s.d < best.d) best = { d: s.d, r, a: s.a, b: s.b } }
    if (!best || best.d > 3) continue
    crossings.push([r2(n.p[0]), r2(n.p[1]), r2(Math.atan2(best.b[0] - best.a[0], best.b[1] - best.a[1])), r2(best.r.w)])
  }

  // ---- kerb bollards (the grey granite hemispheres seen all along the avenue in 2023-25 photos): building-side kerb of the carriageways
  const bollards: number[][] = []
  const avRoads = roads.filter((r) => avenue.includes(r.p))
  for (const r of avRoads) {
    let acc = 0, nextS = 0 // arc length at the start of the segment / of the next bollard
    for (let i = 0; i < r.p.length - 1; i++) {
      const a = r.p[i], b = r.p[i + 1], len = Math.hypot(b[0] - a[0], b[1] - a[1]), tx = (b[0] - a[0]) / len, tz = (b[1] - a[1]) / len
      for (; nextS < acc + len; nextS += 4) {
        const s = nextS - acc
        for (const side of [-1, 1]) {
          const p = [a[0] + tx * s - tz * side * (r.w / 2 + 0.45), a[1] + tz * s + tx * side * (r.w / 2 + 0.45)]
          if (buildings.some((bd) => inside(p, bd.r[0]))) continue
          const bd = Math.min(...buildings.map((q) => Math.min(...q.r[0].map((v) => Math.hypot(v[0] - p[0], v[1] - p[1])))))
          if (bd > 14) continue // only where a building frontage is close (the boulevard side stays clear)
          if (crossings.some((c) => Math.hypot(c[0] - p[0], c[1] - p[1]) < 5)) continue
          bollards.push([r2(p[0]), r2(p[1])])
        }
      }
      acc += len
    }
  }
  return { signs, signTexts: texts, osm, crossings, bollards }
}
